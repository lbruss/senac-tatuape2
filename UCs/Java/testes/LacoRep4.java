package CursoJava;
public class LacoRep4 {
	public static void main(String[] args) {
		System.out.println("Uso do WHILE");
		System.out.println("");
		System.out.println("Contagem do 1 até o 10");
		int num=1;
		while(num<=10) {
			System.out.println(num);
			num++;
		}
		System.out.println("");
		System.out.println("Contagem do 10 até o 1");
		int cont=10;
		while(cont >=1) {
			System.out.println(cont);
			cont--;
		}
	}

}
