package CursoJava;
public class LacoRep2 {
	public static void main(String[] args) {
		System.out.println("Contagem de 0 até 10");
		System.out.println("");
		for (int j=0; j<=10; j++) {
			System.out.println(j);
		}
		System.out.println("");
		
		System.out.println("Contagem de 10 até 0");
		System.out.println("");
		
		for (int j=10; j>=0; j--) {
			System.out.println(j);
		}
		System.out.println("");
	}

}
